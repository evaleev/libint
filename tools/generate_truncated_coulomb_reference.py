#!/usr/bin/env python3
"""Generate independent high-precision truncated-Coulomb test values.

Requires mpmath. Differentiates the defining erf expression at fixed R;
T=0 uses the terminating confluent hypergeometric expression. Production
recurrences, CP2K code, tables and patch boundaries are not used.
"""
import argparse
import math
import random
from pathlib import Path
import mpmath as mp


def reference(r, t, mmax):
    r, t = mp.mpf(r), mp.mpf(t)
    if not t:
        x = r * r
        return [(1 - mp.exp(-x) * mp.hyp1f1(-m, mp.mpf('0.5'), x)) /
                (2 * m + 1) for m in range(mmax + 1)]

    # Taylor-mode automatic differentiation of the defining expression.
    # Guard against factorial scaling and cancellation near the sqrt branch
    # point; this uses no G_m or boundary-derivative recurrence.
    guard = int(mp.log10(mp.factorial(mmax))) + int(
        mmax * max(0, -mp.log10(t))) + 20
    with mp.workdps(mp.mp.dps + guard):
        n = mmax
        root = [mp.sqrt(t)]
        inverse_root = [1 / root[0]]
        for k in range(1, n + 1):
            root.append(root[-1] * (mp.mpf('1.5') - k) / (k * t))
            inverse_root.append(inverse_root[-1] * (mp.mpf('0.5') - k) / (k * t))

        def erfc_jet(shift):
            u = root.copy()
            u[0] += shift
            v = [-mp.fsum(u[j] * u[k-j] for j in range(k+1))
                 for k in range(n+1)]
            exponential = [mp.exp(v[0])]
            for k in range(1, n+1):
                exponential.append(mp.fsum(j*v[j]*exponential[k-j]
                                           for j in range(1, k+1)) / k)
            out = [mp.erfc(u[0])]
            for k in range(1, n+1):
                out.append(-2 / mp.sqrt(mp.pi) / k * mp.fsum(
                    exponential[j] * (k-j) * u[k-j] for j in range(k)))
            return out

        minus, middle, plus = erfc_jet(-r), erfc_jet(0), erfc_jet(r)
        h = [a - 2*b + c for a,b,c in zip(minus, middle, plus)]
        return [(-1)**m * mp.factorial(m) * mp.sqrt(mp.pi) / 4 *
                mp.fsum(h[j] * inverse_root[m-j] for j in range(m+1))
                for m in range(n+1)]



def boys(t, mmax):
    t = mp.mpf(t)
    if not t:
        return [mp.mpf(1) / (2 * m + 1) for m in range(mmax + 1)]
    return [mp.gammainc(m + mp.mpf('0.5'), 0, t) / (2 * t**(m + mp.mpf('0.5')))
            for m in range(mmax + 1)]


def vrr_geometries(count, seed=20261025):
    """Physical primitive geometries across the cutoff transition.

    Exponents zeta (bra) and eta (ket) are log-uniform in [1e-2, 1e6], the
    cutoff Rc log-uniform in [1, 100], and sqrt(T) - R uniform in [-16, 16],
    with R = Rc sqrt(rho), rho = zeta eta / (zeta + eta). W - P is the
    Obara-Saika displacement for |PQ| = sqrt(T / rho). The first entries are
    the worst cases of a 20000-geometry survey.
    """
    def geometry(zeta, eta, rc, d):
        rho = zeta * eta / (zeta + eta)
        r = rc * math.sqrt(rho)
        s = r + d
        if s < 0 or r > 1e4:
            return None
        return zeta, rho, eta / (zeta + eta) * s / math.sqrt(rho), r, s * s

    out = [geometry(*g) for g in [(0.0112, 383, 8.65, 0.983),
                                  (0.145, 1.26e5, 2.16, -0.0582),
                                  (9.92e3, 8.12e4, 2.34, -4.32)]]
    rng = random.Random(seed)
    while len(out) < count:
        g = geometry(10**rng.uniform(-2, 6), 10**rng.uniform(-2, 6),
                     10**rng.uniform(0, 2), rng.uniform(-16, 16))
        if g:
            out.append(g)
    return out


def write_vrr(path, dps, mmax, count):
    out = ['// Generated by tools/generate_truncated_coulomb_reference.py --vrr-output',
           f'// mpmath {mp.__version__}; decimal precision {dps}; mmax {mmax}.',
           '// G_m(R, T) for physical geometries across the cutoff transition;',
           '// zeta, rho and W-P define the (L0|00) Obara-Saika recurrence.',
           '// clang-format off',
           'struct TruncatedCoulombVRRReference {',
           '  double zeta, rho, wp, r, t;', f'  double g[{mmax + 1}];', '};',
           'static const TruncatedCoulombVRRReference truncated_coulomb_vrr_reference[] = {']
    for zeta, rho, wp, r, t in vrr_geometries(count):
        values = reference(r, t, mmax)
        with mp.workdps(dps + 40):
            refined = reference(r, t, mmax)
            f = boys(t, mmax)
        # Stable to 1e-40 relative to the Coulomb scale max(|G_m|, F_m).
        for a, b, c in zip(values, refined, f):
            assert abs(a - b) <= mp.mpf('1e-40') * max(abs(b), c)
        out.append('  {' + ', '.join(format(v, '.17g') for v in (zeta, rho, wp, r, t)) + ', {')
        out.extend('    ' + ', '.join(format(float(v), '.17g') for v in values[k:k+4]) + ','
                   for k in range(0, len(values), 4))
        out.append('  }},')
    out.append('};')
    out.append('// clang-format on')
    path.write_text('\n'.join(out) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    unit_dir = Path('export/tests/unit')
    if not unit_dir.is_dir():
        unit_dir = Path('tests/unit')
    parser.add_argument('--output', type=Path,
                        default=unit_dir / 'truncated-coulomb-reference.h')
    parser.add_argument('--dps', type=int, default=100)
    parser.add_argument('--mmax', type=int, default=64)
    parser.add_argument('--vrr-output', type=Path,
                        help='write the (L0|00) geometry set instead, mmax 16')
    parser.add_argument('--vrr-count', type=int, default=96)
    args = parser.parse_args()
    mp.mp.dps = args.dps
    if args.vrr_output:
        write_vrr(args.vrr_output, args.dps, 16, args.vrr_count)
        return
    points = [('0.00000001', '0'), ('0.1', '0'), ('1', '0'), ('3', '0'),
              ('0.1', '0.1'), ('1', '1'), ('3', '1.000001'),
              ('1', '5'), ('3', '15'), ('5', '24'), ('5', '24.000001'),
              ('5', '24.001'), ('8', '64'), ('8.000001', '64'),
              ('5', '32'), ('5', '32.000001'), ('6', '36.000001'),
              ('10', '40'), ('20', '400'), ('100', '10000')]
    out = ['// Generated by tools/generate_truncated_coulomb_reference.py',
           f'// mpmath {mp.__version__}; decimal precision {args.dps}; mmax {args.mmax}.',
           '// Independent mathematical reference; rounded once to double.',
           '// clang-format off',
           'struct TruncatedCoulombReference {', '  double r, t;',
           f'  double g[{args.mmax + 1}];', '};',
           'static const TruncatedCoulombReference truncated_coulomb_reference[] = {']
    for r, t in points:
        values = reference(float(r), float(t), args.mmax)
        # Verify stability under an additional 40 decimal working digits.
        with mp.workdps(args.dps + 40):
            refined = reference(float(r), float(t), args.mmax)
            assert max(abs(a-b) for a, b in zip(values, refined)) < mp.mpf('1e-80')
        out.append('  {' + r + ', ' + t + ', {')
        out.extend('    ' + ', '.join(format(float(v), '.17g') for v in values[k:k+4]) + ','
                   for k in range(0, len(values), 4))
        out.append('  }},')
        print(f'generated R={r}, T={t}', flush=True)
    out.append('};')
    out.append('// clang-format on')
    args.output.write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
