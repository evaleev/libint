// Tests the disambiguation of the file names that differ only in case at the
// end of the code generation (see CodegenJobs): the suffixes follow the
// lexicographic order of the names, the files are renamed (also in place,
// where names may be swapped), and their include directives are mapped.
// The case-insensitive filesystems of macOS and Windows are the reason for the
// suffixes, hence this test must pass on them and on case-sensitive ones.

#include <codegen_jobs.h>

#include <algorithm>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <random>
#include <set>
#include <sstream>
#include <string>
#include <vector>

namespace fs = std::filesystem;
using libint2::detail::FilenameMapper;
using libint2::detail::NameMap;

namespace {

int nfailed = 0;

#define CHECK_EQ(a, b)                                                     \
  do {                                                                     \
    const auto& a_ = (a);                                                  \
    const auto& b_ = (b);                                                  \
    if (!(a_ == b_)) {                                                     \
      std::cerr << __FILE__ << ":" << __LINE__ << ": " #a " == " #b "\n"   \
                << "  got:      " << a_ << "\n  expected: " << b_ << "\n"; \
      ++nfailed;                                                           \
    }                                                                      \
  } while (0)

void write_file(const fs::path& p, const std::string& contents) {
  std::ofstream o(p);
  o << contents;
}

std::string read_file(const fs::path& p) {
  std::ifstream in(p);
  std::ostringstream oss;
  oss << in.rdbuf();
  return oss.str();
}

/// @return the names of the files in @p dir, as stored, sorted
std::string list_dir(const fs::path& dir) {
  std::vector<std::string> names;
  for (auto& entry : fs::directory_iterator(dir))
    names.push_back(entry.path().filename().string());
  std::sort(names.begin(), names.end());
  std::string result;
  for (auto& n : names) result += n + " ";
  return result;
}

// names that differ only in case, as label_to_name() can produce them
const std::set<std::string> names{"aB", "ab", "Ab", "x"};

void test_final_filenames() {
  const auto final = libint2::detail::final_filenames(names);
  // lexicographic order: "Ab" < "aB" < "ab"
  CHECK_EQ(final.at("Ab"), std::string("Ab"));
  CHECK_EQ(final.at("aB"), std::string("aB-1"));
  CHECK_EQ(final.at("ab"), std::string("ab-2"));
  CHECK_EQ(final.at("x"), std::string("x"));
  CHECK_EQ(final.size(), names.size());
}

void test_map_include() {
  const auto final = libint2::detail::final_filenames(names);
  // a process saw the names in the order ab, aB, Ab
  const NameMap local{{"ab", "ab"}, {"aB", "aB-1"}, {"Ab", "Ab-2"}};
  const FilenameMapper mapper("w/", local, final);
  CHECK_EQ(mapper.renames, true);
  CHECK_EQ(mapper.map_include("#include <w/ab.h>", "src/"),
           std::string("#include <src/ab-2.h>"));
  CHECK_EQ(mapper.map_include("#include <Ab-2.h>", ""),
           std::string("#include <Ab.h>"));
  CHECK_EQ(mapper.map_include("#include <aB-1.cc> // x", ""),
           std::string("#include <aB-1.cc> // x"));
  // not generated by the process: only the directory is mapped
  CHECK_EQ(mapper.map_include("#include <libint2.h>", ""),
           std::string("#include <libint2.h>"));
  CHECK_EQ(mapper.map_include("#include <w/other.h>", "src/"),
           std::string("#include <src/other.h>"));
  // not an include directive at the start of a line
  CHECK_EQ(mapper.map_include("  #include <ab.h>", ""),
           std::string("  #include <ab.h>"));
  CHECK_EQ(mapper.map_include("ab();", ""), std::string("ab();"));

  // a process whose names need no suffixes
  const FilenameMapper identity("w/", NameMap{{"x", "x"}}, final);
  CHECK_EQ(identity.renames, false);
}

void test_finalize_in_place(const fs::path& root) {
  // the serial generator: the files are renamed in the source directory, and
  // "ab" -> "ab-2" and "Ab-2" -> "Ab" are swapped (on a case-insensitive
  // filesystem ab.h and Ab.h are the same file)
  const fs::path dir = root / "in-place";
  fs::create_directories(dir);
  const std::string prefix = dir.string() + "/";
  write_file(dir / "ab.h", "#include <Ab-2.h>\n#include <x.h>\nab\n");
  write_file(dir / "aB-1.cc", "aB\n");
  write_file(dir / "Ab-2.h", "Ab\n");
  write_file(dir / "x.h", "#include <ab.h>\nx\n");
  const NameMap local{{"ab", "ab"}, {"aB", "aB-1"}, {"Ab", "Ab-2"}, {"x", "x"}};
  const FilenameMapper mapper(prefix, local,
                              libint2::detail::final_filenames(names));
  libint2::detail::finalize_files(mapper, local, prefix);
  CHECK_EQ(list_dir(dir), std::string("Ab.h aB-1.cc ab-2.h x.h "));
  CHECK_EQ(read_file(dir / "ab-2.h"),
           std::string("#include <Ab.h>\n#include <x.h>\nab\n"));
  CHECK_EQ(read_file(dir / "aB-1.cc"), std::string("aB\n"));
  CHECK_EQ(read_file(dir / "Ab.h"), std::string("Ab\n"));
  CHECK_EQ(read_file(dir / "x.h"), std::string("#include <ab-2.h>\nx\n"));
}

void test_finalize_from_worker(const fs::path& root) {
  // a worker wrote into its own directory and saw only one of the names
  const fs::path worker = root / "worker";
  const fs::path src = root / "src";
  fs::create_directories(worker);
  fs::create_directories(src);
  const std::string worker_prefix = worker.string() + "/";
  const std::string prefix = src.string() + "/";
  write_file(worker / "ab.cc", "#include <ab.h>\nab\n");
  write_file(worker / "ab.h", "ab\n");
  const NameMap local{{"ab", "ab"}};
  const FilenameMapper mapper(worker_prefix, local,
                              libint2::detail::final_filenames(names));
  libint2::detail::finalize_files(mapper, local, prefix);
  CHECK_EQ(list_dir(worker), std::string(""));
  CHECK_EQ(list_dir(src), std::string("ab-2.cc ab-2.h "));
  CHECK_EQ(read_file(src / "ab-2.cc"), std::string("#include <ab-2.h>\nab\n"));
}

}  // namespace

int main() {
  const fs::path root =
      fs::temp_directory_path() /
      ("libint-test-codegen-files-" + std::to_string(std::random_device{}()));
  fs::remove_all(root);
  try {
    test_final_filenames();
    test_map_include();
    test_finalize_in_place(root);
    test_finalize_from_worker(root);
  } catch (std::exception& e) {
    std::cerr << "exception: " << e.what() << std::endl;
    ++nfailed;
  }
  fs::remove_all(root);
  if (nfailed) {
    std::cerr << nfailed << " check(s) failed" << std::endl;
    return 1;
  }
  std::cout << "all checks passed" << std::endl;
  return 0;
}
